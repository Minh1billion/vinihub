import uuid
from datetime import datetime
from typing import Any, AsyncIterator, Protocol


class ModelDriver(Protocol):
    def chat_stream(self, model: str, messages: list[dict]) -> AsyncIterator[str]: ...
    async def image(
        self, model: str, prompt: str, image_config: dict, references: list[str]
    ) -> tuple[bytes, str]: ...
    async def video_submit(self, model: str, request: dict) -> str: ...
    async def video_status(self, job_id: str) -> dict: ...
    async def download(self, url: str) -> bytes: ...


class ObjectStorage(Protocol):
    async def ensure_bucket(self) -> None: ...
    async def put(self, key: str, data: bytes, mime: str) -> None: ...
    async def get(self, key: str) -> bytes: ...
    async def delete(self, key: str) -> None: ...
    def url(self, key: str, expires: int = 3600) -> str: ...


class BillingGateway(Protocol):
    async def create_checkout(self, user_id: str, plan_id: str) -> dict: ...
    async def cancel(self, user_id: str) -> None: ...


class Mailer(Protocol):
    async def send(self, to: str, subject: str, text: str, html: str | None = None) -> None:
        ...


class JobQueue(Protocol):
    async def enqueue(self, kind: str, payload: dict, *, workspace_id: uuid.UUID | None = None,
                      user_id: uuid.UUID | None = None, priority: int = 0, run_at: datetime | None = None,
                      dedupe_key: str | None = None, db: Any = None) -> uuid.UUID: ...
    async def get(self, job_id: uuid.UUID) -> dict | None: ...
    async def cancel(self, job_id: uuid.UUID) -> bool: ...
